import { chromium } from '/home/user/RSVPFrontend/node_modules/playwright/index.mjs';
import { readFileSync, mkdirSync } from 'node:fs';
import assert from 'node:assert/strict';
// Carpeta de trabajo (state.json de la siembra); la salida va a R6B_OUT. Arranque y precondiciones: docs/progress/R6b-FE-reportes.md.
const DIR = process.env.R6B_DIR ?? '/var/tmp/r6b';
const OUT = process.env.R6B_OUT ?? `${DIR}/shots`;
const st = JSON.parse(readFileSync(`${DIR}/state.json`, 'utf8'));
mkdirSync(OUT, { recursive: true });
// Las sesiones de la siembra caducan a los 15 min: se piden de nuevo (login real de Identity).
const login = async (email) => (await (await fetch('http://localhost:8000/identity/auth/login', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ email, password: 'Correct-horse-9battery' }) })).json()).accessToken;
st.tokenA = await login('r6b-prov-a@example.test'); st.tokenAdmin = await login('e2e-admin@example.test');
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox'] });
const M = new Date().toISOString().slice(0, 7);
const api = async (path, tok) => (await fetch('http://localhost:8000' + path, { headers: { authorization: 'Bearer ' + tok } })).json();
const repA = await api(`/providers/${st.A.providerId}/leads/report?month=${M}`, st.tokenA);
const pa = repA.providers[0];
const adminRep = await api(`/providers/admin/leads/report?month=${M}`, st.tokenAdmin);
const pb = adminRep.providers.find((p) => p.providerId === st.B.providerId);
console.log('esperado (servicio): A', pa.validLeads, pa.invalidLeads, pa.billableLeads, '| B', pb.validLeads, pb.invalidLeads, '| filas admin', adminRep.rows.length);
const log = (m) => console.log('  ✔ ' + m);
const bodyText = (p) => p.evaluate(() => document.body.innerText);
// ---- provider portal
{
  const ctx = await browser.newContext({ viewport: { width: 1100, height: 1400 }, locale: 'es-BO' });
  const page = await ctx.newPage();
  const bad = []; page.on('response', (r) => { if (r.status() >= 400 && r.url().includes(':8000')) bad.push(`${r.status()} ${r.url().replace('http://localhost:8000', '')}`); });
  await page.goto('http://localhost:8081/portal/leads', { waitUntil: 'domcontentloaded' });
  await page.getByText('Producto: Catering Dulce Sol').first().waitFor({ timeout: 90000 });
  const rows = await page.locator('[data-testid^="lead-"]:not([data-testid^="lead-filter"])').count();
  console.log('lead rows', rows);
  const t = await bodyText(page);
  assert.match(t, /Toque de tu propio negocio/i); assert.match(t, /Vista previa/i); assert.match(t, /Duplicado/i);
  assert.match(t, /Tipo de evento: Boda/); assert.match(t, /Ciudad: La Paz/);
  assert.doesNotMatch(t, /celebrationId|guestId/);
  log('/portal/leads: producto, botón, fecha, tipo de evento, ciudad y motivos (propio negocio, vista previa, duplicado)');
  await page.screenshot({ path: `${OUT}/portal-leads.png`, fullPage: true });
  await page.getByTestId('filter-destination').selectOption('OFFICIAL_SITE');
  await page.waitForFunction(() => document.body.innerText.includes('Tipo de evento: Cumpleaños'));
  assert.ok((await page.getByText('Producto: Catering Dulce Sol').count()) >= 1);
  log('/portal/leads con filtro Botón=Sitio web: 1 toque (Cumpleaños)');
  await page.screenshot({ path: `${OUT}/portal-leads-filtrado.png`, fullPage: true });
  await page.goto('http://localhost:8081/portal/metricas', { waitUntil: 'domcontentloaded' });
  await page.getByTestId('report-totals').waitFor({ timeout: 90000 });
  const tot = await page.getByTestId('report-totals').innerText();
  console.log(tot.replace(/\n/g, ' | '));
  assert.match(tot, new RegExp(`Válidos: ${pa.validLeads}\\b`, 'i')); assert.match(tot, new RegExp(`No válidos: ${pa.invalidLeads}\\b`, 'i')); assert.match(tot, new RegExp(`Cobrables: ${pa.billableLeads}\\b`, 'i'));
  assert.match(tot, /Duplicado.*: 1/i); assert.match(tot, new RegExp(`Vista previa: ${pa.invalidByReason.PREVIEW}\\b`, 'i')); assert.match(tot, /Toque de tu propio negocio: 1/i);
  const zone = await page.getByText(/zona horaria de tu negocio/).innerText(); console.log(zone);
  const rowsR = await page.getByTestId('report-row').allInnerTexts(); console.log(rowsR.map((r) => r.replace(/\n/g, ' | ')));
  log('/portal/metricas: reporte mensual cuadra con los clics (4 válidos, 3 no válidos, 4 cobrables)');
  await page.getByTestId('filter-destination').selectOption('OFFICIAL_SITE');
  await page.waitForFunction(() => /Válidos: [01]\b/i.test(document.body.innerText));
  await page.screenshot({ path: `${OUT}/portal-metricas.png`, fullPage: true });
  log('/portal/metricas con filtro Botón: 1 válido');
  console.log('4xx/5xx del gateway durante el recorrido del proveedor:', bad);
  await ctx.close();
}
// ---- admin
{
  const ctx = await browser.newContext({ viewport: { width: 1100, height: 2200 }, locale: 'es-BO', acceptDownloads: true });
  const page = await ctx.newPage();
  await page.goto('http://localhost:8100/admin/metricas', { waitUntil: 'domcontentloaded' });
  await page.getByTestId(`admin-lead-totals-${st.A.providerId}`).waitFor({ timeout: 90000 });
  const a = await page.getByTestId(`admin-lead-totals-${st.A.providerId}`).innerText();
  const b = await page.getByTestId(`admin-lead-totals-${st.B.providerId}`).innerText();
  console.log(a.replace(/\n/g, ' | ')); console.log(b.replace(/\n/g, ' | '));
  assert.match(a, /Dulce Sol R6b/); assert.match(a, new RegExp(`Válidos: ${pa.validLeads}\\b`, 'i')); assert.match(a, new RegExp(`No válidos: ${pa.invalidLeads}\\b`, 'i')); assert.match(a, new RegExp(`Cobrables: ${pa.billableLeads}\\b`, 'i'));
  assert.match(b, /Flores Andes R6b/); assert.match(b, new RegExp(`Válidos: ${pb.validLeads}\\b`, 'i')); assert.match(b, new RegExp(`Cobrables: ${pb.billableLeads}\\b`, 'i'));
  assert.equal(await page.getByTestId('report-row').count(), adminRep.rows.length);
  const filas = await page.getByTestId('report-row').allInnerTexts();
  console.log(filas.map((f) => f.replace(/\n/g, ' | ')));
  assert.ok(filas.some((f) => f.includes('Catering Dulce Sol · WhatsApp') && f.includes('3 válidos · 3 no válidos')), 'fila de WhatsApp de A: producto · botón y cifras');
  assert.ok(filas.some((f) => f.includes('Catering Dulce Sol · Sitio web') && f.includes('1 válidos · 0 no válidos')));
  assert.ok(filas.some((f) => f.includes('Catering Flores Andes · WhatsApp') && f.includes('2 válidos · 0 no válidos')));
  assert.equal(await page.evaluate(() => /leadReport\./.test(document.body.innerText)), false, 'ninguna clave cruda');
  log('/admin/metricas: totales por proveedor y 3 filas (producto y botón)');
  await page.screenshot({ path: `${OUT}/admin-metricas.png`, fullPage: true });
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByTestId('admin-lead-csv').click()]);
  const path = `${OUT}/leads-descargado.csv`; await download.saveAs(path);
  const csv = readFileSync(path, 'utf8');
  const api = await (await fetch(`http://localhost:8000/providers/admin/leads/report.csv?month=${new Date().toISOString().slice(0, 7)}`, { headers: { authorization: 'Bearer ' + st.tokenAdmin } })).text();
  console.log('archivo:', download.suggestedFilename());
  console.log(csv);
  assert.equal(csv.replace(/^﻿/, '').replace(/\r\n/g, '\n'), api.replace(/^﻿/, '').replace(/\r\n/g, '\n'));
  assert.equal(csv.startsWith('﻿'), true); assert.equal((csv.match(/﻿/g) ?? []).length, 1);
  const lines = csv.trim().split(/\r?\n/);
  assert.equal(lines.length, 1 + adminRep.rows.length);
  const sum = (col) => lines.slice(1).reduce((n, l) => n + Number(l.split(',')[col]), 0);
  assert.equal(sum(6), adminRep.providers.reduce((n, p) => n + p.validLeads, 0)); assert.equal(sum(7), adminRep.providers.reduce((n, p) => n + p.invalidLeads, 0));
  log('CSV descargado: filas, válidos y no válidos iguales a los del servicio, un solo BOM, idéntico al del servicio');
  await page.getByTestId('admin-lead-provider').selectOption(st.B.providerId);
  assert.equal(await page.getByTestId('report-row').count(), adminRep.rows.filter((r) => r.providerId === st.B.providerId).length);
  log('filtro por proveedor: sus filas');
  await ctx.close();
}
await browser.close();
console.log('RECORRIDO OK');
