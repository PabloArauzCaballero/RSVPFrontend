// Vendored backend OpenAPI 3.1 specs and the types generated from them.
//
// The copy is pinned to ONE commit of the backend repository, recorded in backend.lock.json (repository, ref, and the
// version + sha256 of every spec). Nothing here reads the working tree of a backend checkout: a sibling RSVPBackend on
// another branch can no longer turn this check red or green.
//
//   node scripts/generate.mjs --check          offline: specs/ equals backend.lock.json and src/generated is fresh
//   node scripts/generate.mjs --verify-source  backend.lock.json equals the backend repository at its pinned ref
//   node scripts/generate.mjs [--ref <ref>]    vendor the specs of <ref> (default: the pinned ref), rewrite the lock,
//                                              regenerate src/generated
//
// Backend source (for --verify-source and for vendoring), first match wins:
//   RSVP_BACKEND_REPO=<path>   a git clone of the backend; read with `git show <sha>:<path>` (never its working tree)
//   RSVP_BACKEND_TOKEN | GH_TOKEN | GITHUB_TOKEN
//                              GitHub REST API, contents at the pinned commit (read access to the backend repository)
// With neither, --verify-source fails: CI cannot pass without proving the copy.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync } from 'node:fs';
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const vendored = join(root, 'specs');
const generated = join(root, 'src', 'generated');
const lockFile = join(root, 'backend.lock.json');
const banner = '// GENERATED by packages/contracts/scripts/generate.mjs from the frozen backend OpenAPI specs. Do not edit.\n';
const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');
const names = (files) => files.filter((f) => f.endsWith('.openapi.json')).map((f) => f.replace('.openapi.json', '')).sort();
const argument = (flag) => {
  const index = process.argv.indexOf(flag);
  return index === -1 ? undefined : process.argv[index + 1];
};

/** Where the backend specs come from. Each source reads the specs of an exact commit. */
function backendSource(lock) {
  const repo = process.env.RSVP_BACKEND_REPO;
  if (repo) {
    const git = (...args) => execFileSync('git', ['-C', repo, ...args], { encoding: 'buffer', stdio: ['ignore', 'pipe', 'pipe'] });
    return {
      label: `git objects of ${repo}`,
      resolve: async (ref) => git('rev-parse', '--verify', `${ref}^{commit}`).toString('utf8').trim(),
      list: async (sha) => names(git('ls-tree', '--name-only', `${sha}:${lock.path}`).toString('utf8').split('\n')),
      read: async (sha, name) => git('show', `${sha}:${lock.path}/${name}.openapi.json`),
    };
  }
  const token = process.env.RSVP_BACKEND_TOKEN || process.env.GH_TOKEN || process.env.GITHUB_TOKEN;
  if (token) {
    const api = async (path, accept) => {
      const response = await fetch(`https://api.github.com/repos/${lock.repository}/${path}`, {
        headers: { authorization: `Bearer ${token}`, accept, 'x-github-api-version': '2022-11-28', 'user-agent': 'rsvp-contracts-check' },
        signal: AbortSignal.timeout(20_000),
      });
      if (!response.ok) throw new Error(`GitHub API ${response.status} for ${lock.repository}/${path}: the token needs read access to the backend repository`);
      return response;
    };
    return {
      label: `GitHub API (${lock.repository})`,
      resolve: async (ref) => (await (await api(`commits/${encodeURIComponent(ref)}`, 'application/vnd.github+json')).json()).sha,
      list: async (sha) => names((await (await api(`contents/${lock.path}?ref=${sha}`, 'application/vnd.github+json')).json()).map((entry) => entry.name)),
      read: async (sha, name) => Buffer.from(await (await api(`contents/${lock.path}/${name}.openapi.json?ref=${sha}`, 'application/vnd.github.raw+json')).arrayBuffer()),
    };
  }
  return undefined;
}

async function generateTypes(specNames, check) {
  const problems = [];
  if (!check) {
    await rm(generated, { recursive: true, force: true });
    await mkdir(generated, { recursive: true });
  }
  const manifest = {};
  for (const name of specNames) {
    const text = await readFile(join(vendored, `${name}.openapi.json`), 'utf8');
    const output = banner + astToString(await openapiTS(JSON.parse(text), { alphabetize: true }));
    manifest[name] = sha256(text).slice(0, 16);
    const file = join(generated, `${name}.ts`);
    if (check) {
      const current = existsSync(file) ? await readFile(file, 'utf8') : undefined;
      if (current !== output) problems.push(`src/generated/${name}.ts is stale: run "yarn workspace @rsvp/contracts generate"`);
    } else await writeFile(file, output);
  }
  const camel = (name) => name.split('-').map((p, i) => (i ? p[0].toUpperCase() + p.slice(1) : p)).join('');
  const pascal = (name) => { const c = camel(name); return c[0].toUpperCase() + c.slice(1); };
  const index = banner + specNames.map((n) => `export type { paths as ${pascal(n)}Paths, components as ${pascal(n)}Components, operations as ${pascal(n)}Operations } from './${n}.js';`).join('\n') + `\n\nexport const contractVersions = ${JSON.stringify(manifest, null, 2)} as const;\n`;
  const indexFile = join(generated, 'index.ts');
  if (check) {
    const current = existsSync(indexFile) ? await readFile(indexFile, 'utf8') : undefined;
    if (current !== index) problems.push('src/generated/index.ts is stale');
  } else await writeFile(indexFile, index);
  return problems;
}

/** Offline: the vendored specs are exactly the ones recorded in the lock. */
async function checkVendored(lock) {
  const problems = [];
  const present = names(await readdir(vendored));
  const locked = Object.keys(lock.specs).sort();
  if (JSON.stringify(present) !== JSON.stringify(locked)) problems.push(`specs/ holds [${present.join(', ')}] but backend.lock.json pins [${locked.join(', ')}]`);
  for (const name of present.filter((value) => lock.specs[value])) {
    const bytes = await readFile(join(vendored, `${name}.openapi.json`));
    const version = JSON.parse(bytes.toString('utf8')).info?.version;
    if (sha256(bytes) !== lock.specs[name].sha256 || version !== lock.specs[name].version)
      problems.push(`specs/${name}.openapi.json (${version}) differs from ${lock.repository}@${lock.ref.slice(0, 12)} (${lock.specs[name].version}) recorded in backend.lock.json: run "yarn workspace @rsvp/contracts generate"`);
  }
  return problems;
}

/** The lock describes the backend repository at its pinned ref (same file list, same bytes). */
async function verifySource(lock, source) {
  const problems = [];
  if (!/^[0-9a-f]{40}$/.test(lock.ref)) return [`backend.lock.json ref must be a full commit sha, found "${lock.ref}"`];
  const remote = await source.list(lock.ref);
  const locked = Object.keys(lock.specs).sort();
  if (JSON.stringify(remote) !== JSON.stringify(locked)) problems.push(`${lock.repository}@${lock.ref.slice(0, 12)} has specs [${remote.join(', ')}] but backend.lock.json pins [${locked.join(', ')}]`);
  for (const name of remote.filter((value) => lock.specs[value])) {
    if (sha256(await source.read(lock.ref, name)) !== lock.specs[name].sha256)
      problems.push(`${name}: backend.lock.json does not match ${lock.repository}@${lock.ref.slice(0, 12)}`);
  }
  return problems;
}

async function vendor(lock, source, ref) {
  const sha = await source.resolve(ref);
  const specNames = await source.list(sha);
  if (specNames.length === 0) throw new Error(`No OpenAPI specs at ${lock.repository}@${sha}:${lock.path}`);
  for (const name of names(await readdir(vendored))) if (!specNames.includes(name)) await rm(join(vendored, `${name}.openapi.json`));
  const specs = {};
  for (const name of specNames) {
    const bytes = await source.read(sha, name);
    await writeFile(join(vendored, `${name}.openapi.json`), bytes);
    specs[name] = { version: JSON.parse(bytes.toString('utf8')).info.version, sha256: sha256(bytes) };
  }
  const next = { ...lock, ref: sha, refName: ref === lock.ref ? lock.refName : ref, specs };
  await writeFile(lockFile, `${JSON.stringify(next, null, 2)}\n`);
  return next;
}

const lock = JSON.parse(await readFile(lockFile, 'utf8'));
const problems = [];
let mode;
if (process.argv.includes('--check')) {
  mode = 'verified';
  problems.push(...(await checkVendored(lock)));
  problems.push(...(await generateTypes(names(await readdir(vendored)), true)));
} else if (process.argv.includes('--verify-source')) {
  mode = 'verified against the backend';
  const source = backendSource(lock);
  if (!source) problems.push('Cannot verify the copy against the backend: set RSVP_BACKEND_TOKEN (CI secret RSVP_BACKEND_CONTRACTS_TOKEN, read access to the backend repository) or RSVP_BACKEND_REPO=<backend git clone>.');
  else {
    console.log(`[contracts] backend source: ${source.label}, ref ${lock.ref}`);
    problems.push(...(await verifySource(lock, source)));
  }
} else {
  mode = 'generated';
  const source = backendSource(lock);
  if (!source) throw new Error('Set RSVP_BACKEND_REPO=<backend git clone> or RSVP_BACKEND_TOKEN to vendor the backend specs.');
  const next = await vendor(lock, source, argument('--ref') ?? lock.ref);
  console.log(`[contracts] vendored ${lock.repository}@${next.ref} (${next.refName}) from ${source.label}`);
  problems.push(...(await generateTypes(Object.keys(next.specs).sort(), false)));
}

if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
const pinned = JSON.parse(await readFile(lockFile, 'utf8'));
console.log(`[contracts] ${mode} ${Object.keys(pinned.specs).length} contracts at ${pinned.repository}@${pinned.ref.slice(0, 12)}: ${Object.entries(pinned.specs).map(([name, spec]) => `${name} ${spec.version}`).join(', ')}`);
