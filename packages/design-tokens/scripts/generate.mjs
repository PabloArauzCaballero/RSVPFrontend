// Single source of truth: src/*.ts. Emits generated/tokens.json (read by the Tailwind preset for
// seo-web and NativeWind) and generated/tokens.css. `--check` fails if the files are stale.
//   node scripts/generate.mjs [--check]
import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'generated');
const { colors, brand: namedBrand, night, onNight } = await import('../src/colors.ts');
const { spacing, radius, shadow } = await import('../src/spacing.ts');
const { typography } = await import('../src/typography.ts');

const kebab = (name) => name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const rem = (px) => (px === 0 ? '0px' : `${px / 16}rem`);
const toVars = (palette) => Object.fromEntries(Object.entries(palette).map(([k, v]) => [`--${kebab(k)}`, v]));
const brand = { azul: namedBrand.azul, night, 'on-night': onNight, 'azul-osc': namedBrand.azulOsc, 'azul-cl': namedBrand.azulCl, cielo: namedBrand.cielo };

const light = { ...toVars(colors.light), ...Object.fromEntries(Object.entries(brand).map(([k, v]) => [`--${k}`, v])) };
const dark = toVars(colors.dark);
const tokens = {
  colors: Object.fromEntries(Object.keys(light).map((v) => [v.slice(2), `var(${v})`])),
  light, dark,
  spacing: Object.fromEntries(Object.entries(spacing).map(([k, v]) => [k, k === 'px' ? '1px' : rem(v)])),
  borderRadius: Object.fromEntries(Object.entries(radius).map(([k, v]) => [k === 'none' ? 'none' : k, k === 'full' ? '9999px' : rem(v)])),
  boxShadow: shadow,
  fontFamily: {
    sans: [typography.fontFamily.sans, 'system-ui', 'sans-serif'],
    display: [typography.fontFamily.display, typography.fontFamily.sans, 'system-ui', 'sans-serif']
  },
  fontSize: Object.fromEntries(Object.entries(typography.fontSize).map(([k, v]) => [k, [rem(v), { lineHeight: rem(typography.lineHeight[k]) }]]))
};
const block = (selector, vars) => `${selector} {\n${Object.entries(vars).map(([k, v]) => `  ${k}: ${v};`).join('\n')}\n}\n`;
const css = `/* GENERATED by scripts/generate.mjs from src/*.ts. Do not edit. */\n${block(':root', light)}${block("[data-theme='dark']", dark)}@media (prefers-color-scheme: dark) {\n${block(":root:not([data-theme='light'])", dark).replace(/^/gm, '  ').replace(/\s+$/, '\n')}}\n`;
const json = `${JSON.stringify(tokens, null, 2)}\n`;

const files = { 'tokens.json': json, 'tokens.css': css };
const stale = [];
for (const [name, content] of Object.entries(files)) {
  const file = join(out, name);
  if (process.argv.includes('--check')) {
    if (!existsSync(file) || (await readFile(file, 'utf8')) !== content) stale.push(`generated/${name}`);
  } else { await mkdir(out, { recursive: true }); await writeFile(file, content); }
}
if (stale.length) { console.error(`Stale: ${stale.join(', ')}. Run "yarn workspace @rsvp/design-tokens generate".`); process.exit(1); }
console.log(`[design-tokens] ${process.argv.includes('--check') ? 'verified' : 'generated'} ${Object.keys(files).join(', ')}`);
